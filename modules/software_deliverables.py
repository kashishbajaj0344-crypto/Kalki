"""
Software Development Deliverables Generator
==========================================
Generates complete, production-ready apps and games:
- iOS apps (SwiftUI + Xcode project)
- Android apps (Kotlin + Android Studio project)
- Games (Unity C# / Godot GDScript)
- Complete source code, assets, documentation
- Ready to compile and deploy
"""

import os
import json
from typing import Dict, List, Any, Optional
from pathlib import Path
from datetime import datetime
from dataclasses import dataclass, asdict


@dataclass
class AppDeliverables:
    """Complete app deliverables package"""
    project_id: str
    app_name: str
    platform: str  # ios, android, cross-platform
    app_type: str  # productivity, game, social, etc.
    source_files: List[str]
    asset_files: List[str]
    documentation: List[str]
    project_structure: Dict[str, Any]
    monetization_setup: Dict[str, Any]
    deployment_guide: str
    estimated_dev_time: int  # hours
    generated_at: str


class iOSAppGenerator:
    """Generate complete iOS applications"""
    
    def generate_swiftui_app(self, app_spec: Dict[str, Any], output_dir: Path) -> AppDeliverables:
        """Generate complete SwiftUI iOS app"""
        
        app_name = app_spec.get("name", "MyApp")
        app_type = app_spec.get("type", "productivity")
        features = app_spec.get("features", [])
        
        project_id = f"ios_{app_name.lower().replace(' ', '_')}"
        project_dir = output_dir / project_id
        project_dir.mkdir(parents=True, exist_ok=True)
        
        source_files = []
        asset_files = []
        docs = []
        
        # Generate App structure
        app_dir = project_dir / app_name
        app_dir.mkdir(exist_ok=True)
        
        # 1. Main App file
        app_file = self._generate_app_file(app_name, app_dir)
        source_files.append(str(app_file))
        
        # 2. ContentView
        content_view = self._generate_content_view(app_name, app_type, app_dir)
        source_files.append(str(content_view))
        
        # 3. View Models
        if "data" in features:
            viewmodel = self._generate_viewmodel(app_name, app_dir)
            source_files.append(str(viewmodel))
        
        # 4. Models
        models = self._generate_models(app_spec, app_dir)
        source_files.extend(models)
        
        # 5. Network layer (if API feature)
        if "api" in features:
            network = self._generate_network_layer(app_dir)
            source_files.extend(network)
        
        # 6. Assets
        assets_dir = app_dir / "Assets.xcassets"
        assets_dir.mkdir(exist_ok=True)
        asset_catalog = self._generate_asset_catalog(assets_dir)
        asset_files.append(str(asset_catalog))
        
        # 7. Info.plist
        info_plist = self._generate_info_plist(app_name, app_dir)
        source_files.append(str(info_plist))
        
        # 8. Xcode project file
        xcodeproj = self._generate_xcodeproj(app_name, project_dir)
        source_files.append(str(xcodeproj))
        
        # 9. Monetization setup
        monetization = self._setup_ios_monetization(app_spec, app_dir)
        if monetization:
            source_files.append(monetization)
        
        # 10. Documentation
        readme = self._generate_ios_readme(app_name, app_spec, project_dir)
        deployment = self._generate_ios_deployment_guide(app_name, project_dir)
        docs.extend([str(readme), str(deployment)])
        
        return AppDeliverables(
            project_id=project_id,
            app_name=app_name,
            platform="ios",
            app_type=app_type,
            source_files=source_files,
            asset_files=asset_files,
            documentation=docs,
            project_structure=self._get_project_structure(project_dir),
            monetization_setup=self._get_monetization_config(app_spec),
            deployment_guide=str(deployment),
            estimated_dev_time=self._estimate_dev_time(features),
            generated_at=datetime.now().isoformat()
        )
    
    def _generate_app_file(self, app_name: str, app_dir: Path) -> Path:
        """Generate main App.swift file"""
        app_file = app_dir / f"{app_name}App.swift"
        
        content = f"""//
//  {app_name}App.swift
//  {app_name}
//
//  Generated by Kalki AI Design System
//  {datetime.now().strftime('%Y-%m-%d')}
//

import SwiftUI

@main
struct {app_name}App: App {{
    var body: some Scene {{
        WindowGroup {{
            ContentView()
        }}
    }}
}}
"""
        
        app_file.write_text(content)
        return app_file
    
    def _generate_content_view(self, app_name: str, app_type: str, app_dir: Path) -> Path:
        """Generate ContentView.swift"""
        view_file = app_dir / "ContentView.swift"
        
        if app_type == "productivity":
            content = f"""//
//  ContentView.swift
//  {app_name}
//

import SwiftUI

struct ContentView: View {{
    @State private var items: [TodoItem] = []
    @State private var newItemTitle = ""
    
    var body: some View {{
        NavigationView {{
            VStack {{
                // Add item section
                HStack {{
                    TextField("New item", text: $newItemTitle)
                        .textFieldStyle(RoundedBorderTextFieldStyle())
                    
                    Button(action: addItem) {{
                        Image(systemName: "plus.circle.fill")
                            .font(.title)
                    }}
                    .disabled(newItemTitle.isEmpty)
                }}
                .padding()
                
                // Items list
                List {{
                    ForEach(items) {{ item in
                        HStack {{
                            Image(systemName: item.isCompleted ? "checkmark.circle.fill" : "circle")
                                .foregroundColor(item.isCompleted ? .green : .gray)
                            Text(item.title)
                            Spacer()
                        }}
                        .contentShape(Rectangle())
                        .onTapGesture {{
                            toggleItem(item)
                        }}
                    }}
                    .onDelete(perform: deleteItems)
                }}
            }}
            .navigationTitle("{app_name}")
        }}
    }}
    
    private func addItem() {{
        let newItem = TodoItem(title: newItemTitle)
        items.append(newItem)
        newItemTitle = ""
    }}
    
    private func toggleItem(_ item: TodoItem) {{
        if let index = items.firstIndex(where: {{ $0.id == item.id }}) {{
            items[index].isCompleted.toggle()
        }}
    }}
    
    private func deleteItems(at offsets: IndexSet) {{
        items.remove(atOffsets: offsets)
    }}
}}

struct ContentView_Previews: PreviewProvider {{
    static var previews: some View {{
        ContentView()
    }}
}}
"""
        elif app_type == "game":
            content = f"""//
//  ContentView.swift
//  {app_name}
//

import SwiftUI

struct ContentView: View {{
    @State private var score = 0
    @State private var isPlaying = false
    
    var body: some View {{
        ZStack {{
            Color.blue.opacity(0.3).ignoresSafeArea()
            
            VStack(spacing: 30) {{
                Text("{app_name}")
                    .font(.largeTitle)
                    .fontWeight(.bold)
                
                Text("Score: \\(score)")
                    .font(.title)
                
                if isPlaying {{
                    GameView(score: $score)
                }} else {{
                    Button("Start Game") {{
                        isPlaying = true
                        score = 0
                    }}
                    .font(.title2)
                    .padding()
                    .background(Color.green)
                    .foregroundColor(.white)
                    .cornerRadius(10)
                }}
            }}
        }}
    }}
}}

struct GameView: View {{
    @Binding var score: Int
    @State private var position = CGPoint(x: 200, y: 400)
    
    var body: some View {{
        Circle()
            .fill(Color.red)
            .frame(width: 50, height: 50)
            .position(position)
            .onTapGesture {{
                score += 1
                randomizePosition()
            }}
    }}
    
    private func randomizePosition() {{
        position = CGPoint(
            x: CGFloat.random(in: 50...350),
            y: CGFloat.random(in: 100...700)
        )
    }}
}}
"""
        else:
            content = f"""//
//  ContentView.swift
//  {app_name}
//

import SwiftUI

struct ContentView: View {{
    var body: some View {{
        NavigationView {{
            VStack(spacing: 20) {{
                Image(systemName: "star.fill")
                    .font(.system(size: 80))
                    .foregroundColor(.yellow)
                
                Text("Welcome to {app_name}")
                    .font(.title)
                    .fontWeight(.bold)
                
                Text("Your app is ready to customize!")
                    .font(.body)
                    .foregroundColor(.secondary)
                
                Spacer()
            }}
            .padding()
            .navigationTitle("{app_name}")
        }}
    }}
}}
"""
        
        view_file.write_text(content)
        return view_file
    
    def _generate_viewmodel(self, app_name: str, app_dir: Path) -> Path:
        """Generate ViewModel"""
        vm_file = app_dir / "ViewModel.swift"
        
        content = f"""//
//  ViewModel.swift
//  {app_name}
//

import Foundation
import Combine

class ViewModel: ObservableObject {{
    @Published var items: [TodoItem] = []
    @Published var isLoading = false
    
    func fetchData() {{
        isLoading = true
        // Simulate network call
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) {{
            self.items = self.loadSampleData()
            self.isLoading = false
        }}
    }}
    
    private func loadSampleData() -> [TodoItem] {{
        return [
            TodoItem(title: "Sample Item 1"),
            TodoItem(title: "Sample Item 2"),
            TodoItem(title: "Sample Item 3")
        ]
    }}
}}
"""
        
        vm_file.write_text(content)
        return vm_file
    
    def _generate_models(self, app_spec: Dict[str, Any], app_dir: Path) -> List[str]:
        """Generate model files"""
        models = []
        
        # TodoItem model
        model_file = app_dir / "Models.swift"
        content = """//
//  Models.swift
//

import Foundation

struct TodoItem: Identifiable, Codable {
    let id: UUID
    var title: String
    var isCompleted: Bool
    var createdAt: Date
    
    init(id: UUID = UUID(), title: String, isCompleted: Bool = false) {
        self.id = id
        self.title = title
        self.isCompleted = isCompleted
        self.createdAt = Date()
    }}
}
"""
        
        model_file.write_text(content)
        models.append(str(model_file))
        
        return models
    
    def _generate_network_layer(self, app_dir: Path) -> List[str]:
        """Generate networking code"""
        network_dir = app_dir / "Network"
        network_dir.mkdir(exist_ok=True)
        
        files = []
        
        # API Client
        api_file = network_dir / "APIClient.swift"
        content = """//
//  APIClient.swift
//

import Foundation

class APIClient {
    static let shared = APIClient()
    private let baseURL = "https://api.example.com"
    
    func fetch<T: Decodable>(endpoint: String) async throws -> T {
        guard let url = URL(string: baseURL + endpoint) else {
            throw NetworkError.invalidURL
        }
        
        let (data, response) = try await URLSession.shared.data(from: url)
        
        guard let httpResponse = response as? HTTPURLResponse,
              200...299 ~= httpResponse.statusCode else {
            throw NetworkError.invalidResponse
        }
        
        let decoder = JSONDecoder()
        return try decoder.decode(T.self, from: data)
    }
}

enum NetworkError: Error {
    case invalidURL
    case invalidResponse
    case decodingError
}
"""
        
        api_file.write_text(content)
        files.append(str(api_file))
        
        return files
    
    def _generate_asset_catalog(self, assets_dir: Path) -> Path:
        """Generate asset catalog Contents.json"""
        contents = assets_dir / "Contents.json"
        content = {
            "info": {
                "version": 1,
                "author": "kalki"
            }
        }
        
        contents.write_text(json.dumps(content, indent=2))
        return contents
    
